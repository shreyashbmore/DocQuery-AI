"""Run the full DocQuery AI experiment suite and write a Markdown report you can commit.

  python eval/run_experiments.py --docs data/docs --gold eval/gold_qa.jsonl --llm qwen2.5:7b
  python eval/run_experiments.py ... --quick              # smaller grid, for a first check (~minutes)
  python eval/run_experiments.py ... --skip-generation    # retrieval studies only, no LLM needed

Studies
  A  Retrieval methods   chunking (fixed / recursive / semantic) x retrieval (dense / BM25 / hybrid / hybrid+rerank)
  B  Chunk overlap       0-30% overlap x word vs sentence-aligned x near-duplicate removal off / on
  C  End-to-end answers  best overlap from B, hybrid + re-rank, answers generated by each --llm

Outputs
  docs/EXPERIMENTS.md                 latest report (also kept as docs/experiments/<run_id>.md)
  eval/results/run_<run_id>/          study_a.csv, study_b.csv, generation_<model>.csv, run.log, config.yaml
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import logging
import os
import platform
import shutil
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from docquery.cli import _load_env  # noqa: E402
from docquery.config import load_config  # noqa: E402
from docquery.ingest.embedder import build_embedder  # noqa: E402
from docquery.ingest.loaders import iter_paths, load_document  # noqa: E402
from docquery.pipeline import DocQuery  # noqa: E402
from docquery.retrieve.reranker import build_reranker  # noqa: E402
from eval.run_ablation import index_tag, markdown_table, run_grid, write_csv  # noqa: E402
from eval.run_eval import evaluate, load_gold  # noqa: E402

log = logging.getLogger("experiments")
PACKAGES = ["numpy", "rank-bm25", "pymupdf", "sentence-transformers", "torch", "transformers",
            "qdrant-client", "httpx", "fastapi", "streamlit"]


# ------------------------------------------------------------------ helpers
def setup_logging(run_dir: Path) -> None:
    fmt = logging.Formatter("%(asctime)s %(levelname)-7s %(message)s", "%H:%M:%S")
    root = logging.getLogger()
    root.setLevel(logging.INFO)
    for h in (logging.StreamHandler(sys.stdout), logging.FileHandler(run_dir / "run.log")):
        h.setFormatter(fmt)
        root.addHandler(h)
    for noisy in ("httpx", "httpcore", "sentence_transformers", "urllib3", "filelock"):
        logging.getLogger(noisy).setLevel(logging.WARNING)


def environment() -> dict:
    env = {"OS": platform.platform(), "Machine": platform.machine(), "CPU cores": os.cpu_count(),
           "Python": platform.python_version()}
    try:
        import torch
        env["Accelerator"] = "CUDA" if torch.cuda.is_available() else (
            "Apple MPS" if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available() else "CPU")
    except Exception:
        pass
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                                text=True, timeout=5).stdout.strip()
        if commit:
            env["Git commit"] = commit
    except Exception:
        pass
    for pkg in PACKAGES:
        try:
            env[pkg] = md.version(pkg)
        except md.PackageNotFoundError:
            pass
    return env


def check_ollama(models: list[str]) -> None:
    import httpx

    host = os.getenv("OLLAMA_HOST", "http://localhost:11434").rstrip("/")
    try:
        tags = httpx.get(f"{host}/api/tags", timeout=10).json()
    except Exception as e:
        sys.exit(f"Cannot reach Ollama at {host} ({e}). Start it with `ollama serve` or open the Ollama app.")
    have = {m["name"] for m in tags.get("models", [])}
    have |= {n.split(":")[0] for n in have if n.endswith(":latest")}
    missing = [m for m in models if m not in have]
    if missing:
        sys.exit(f"Ollama models not found: {missing}. Run: " + "  ".join(f"ollama pull {m}" for m in missing))


def parse_llm(spec: str) -> tuple[str, str]:
    if spec.startswith(("ollama:", "openai:", "extractive")):
        provider, _, model = spec.partition(":")
        return provider, model or "none"
    return "ollama", spec


def documents_table(docs_dir: str) -> tuple[list[dict], int]:
    rows, words = [], 0
    for path in iter_paths([docs_dir]):
        try:
            secs = load_document(path)
        except Exception as e:
            rows.append({"file": path.name, "pages": "error", "words": str(e)[:40]})
            continue
        n = sum(len(s.text.split()) for s in secs)
        words += n
        rows.append({"file": path.name, "pages": len([s for s in secs if s.page]) or "-", "words": n})
    return rows, words


def gold_stats(gold: list[dict]) -> dict:
    return {"total": len(gold), "answerable": sum(g.get("answerable", True) for g in gold),
            "unanswerable": sum(not g.get("answerable", True) for g in gold),
            "verified": sum(g.get("verified", True) is True for g in gold),
            "by type": dict(Counter(g.get("type", "untyped") for g in gold))}


def pick_overlap(rows: list[dict]) -> dict | None:
    """Best overlap = highest Recall@5, then MRR@10, then the smaller overlap (cheaper index)."""
    cands = [r for r in rows if r["overlap_mode"] == "sentence" and r["dedup"] == "on"] or rows
    if not cands:
        return None
    return sorted(cands, key=lambda r: (-r.get("recall@5", 0), -r.get("mrr@10", 0), r["overlap"]))[0]


def failure_reason(row: dict) -> str | None:
    if not row["answerable"]:
        return None if row.get("abstained") else "answered a question the documents cannot answer"
    if row.get("recall@5") == 0:
        return "retrieval miss: evidence not in top 5"
    if row.get("abstained"):
        return "false refusal: evidence retrieved but the system declined"
    if row.get("token_f1", 1) < 0.25:
        return "low overlap with the expected answer"
    return None


def fmt(v) -> str:
    return f"{v:.3f}" if isinstance(v, float) else str(v)


# ------------------------------------------------------------------ main
def main(argv=None):
    _load_env()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--docs", default="data/docs")
    p.add_argument("--gold", default="eval/gold_qa.jsonl")
    p.add_argument("--llm", action="append", default=[], help="Ollama model (qwen2.5:7b) or provider:model; repeatable")
    p.add_argument("-c", "--config")
    p.add_argument("-o", "--override", action="append", default=[])
    p.add_argument("--quick", action="store_true", help="smaller grid for a first check")
    p.add_argument("--skip-generation", action="store_true", help="retrieval studies only (no LLM)")
    p.add_argument("--max-gen-questions", type=int, help="limit questions in study C (saves time)")
    p.add_argument("--report", default="docs/EXPERIMENTS.md")
    args = p.parse_args(argv)

    run_id = time.strftime("%Y-%m-%d_%H%M%S")
    run_dir = ROOT / "eval" / "results" / f"run_{run_id}"
    run_dir.mkdir(parents=True, exist_ok=True)
    setup_logging(run_dir)
    t_start = time.time()
    cmd = "python eval/run_experiments.py " + " ".join(argv if argv is not None else sys.argv[1:])
    log.info("Run %s started: %s", run_id, cmd)

    base = load_config(args.config, args.override)
    llm_specs = [] if args.skip_generation else (args.llm or ["qwen2.5:7b"])
    llms = [parse_llm(s) for s in llm_specs]
    if any(p_ == "ollama" for p_, _ in llms):
        check_ollama([m for p_, m in llms if p_ == "ollama"])

    gold = load_gold(args.gold)
    gstats = gold_stats(gold)
    doc_rows, total_words = documents_table(args.docs)
    if not doc_rows:
        sys.exit(f"No documents found in {args.docs}")
    log.info("Documents: %d files, %d words. Gold: %s", len(doc_rows), total_words, gstats)
    (run_dir / "config.yaml").write_text(yaml.safe_dump(base, sort_keys=False))

    log.info("Loading embedding model %s and re-ranker %s ...", base["embedding"]["model"], base["reranker"]["model"])
    embedder = build_embedder(base["embedding"])
    reranker = build_reranker({**base["reranker"], "enabled": True})
    env = environment()
    env["Embedding model"] = embedder.name
    env["Re-ranker"] = getattr(reranker, "name", base["reranker"]["model"])
    timings = {}

    # ---------------- Study A: retrieval methods
    t0 = time.time()
    log.info("=== Study A: retrieval methods ===")
    study_a = run_grid(base, gold, args.docs, embedder, reranker,
                       chunking=["recursive"] if args.quick else ["fixed", "recursive", "semantic"],
                       dedup=["on"], log=log.info)
    write_csv(study_a, run_dir / "study_a.csv")
    timings["Study A"] = time.time() - t0

    # ---------------- Study B: chunk overlap
    t0 = time.time()
    log.info("=== Study B: chunk overlap ===")
    overlaps = [0, 0.2] if args.quick else [0, 0.1, 0.2, 0.3]
    study_b = run_grid(base, gold, args.docs, embedder, reranker, chunking=["recursive"], overlaps=overlaps,
                       modes=["word", "sentence"], dedup=["off", "on"], retrieval=["hybrid+rerank"], log=log.info)
    write_csv(study_b, run_dir / "study_b.csv")
    timings["Study B"] = time.time() - t0
    best = pick_overlap(study_b)

    def find(overlap, mode, dedup):
        return next((r for r in study_b if r["overlap"] == overlap and r["overlap_mode"] == mode
                     and r["dedup"] == dedup), None)

    # ---------------- Study C: end-to-end generation
    study_c, failures = [], []
    chosen_overlap = best["overlap"] if best else base["chunking"]["overlap"]
    if llms:
        t0 = time.time()
        log.info("=== Study C: end-to-end answers (overlap %s, sentence-aligned, hybrid + re-rank, dedup on) ===",
                 chosen_overlap)
        chunk_cfg = {**base["chunking"], "strategy": "recursive", "overlap": chosen_overlap, "overlap_mode": "sentence"}
        cfg = {**base, "index_dir": str(ROOT / "index" / "ablation" / index_tag(args.docs, chunk_cfg, embedder)),
               "chunking": chunk_cfg,
               "retrieval": {**base["retrieval"], "mode": "hybrid",
                             "dedup_threshold": base["retrieval"].get("dedup_threshold") or 0.8}}
        questions = gold[:args.max_gen_questions] if args.max_gen_questions else gold
        for provider, model in llms:
            dq = DocQuery({**cfg, "llm": {**cfg["llm"], "provider": provider, "model": model}},
                          embedder=embedder, reranker=reranker)
            if not dq.chunks:
                dq.ingest([args.docs])
            try:  # warm-up so model loading time is not counted as latency
                dq.llm.chat([{"role": "user", "content": "Reply with OK."}])
            except Exception as e:
                sys.exit(f"LLM {provider}:{model} failed: {e}")
            log.info("Generating answers with %s:%s for %d questions ...", provider, model, len(questions))
            summary, rows = evaluate(dq, questions, retrieval_only=False)
            safe = model.replace(":", "_").replace("/", "_")
            write_csv(rows, run_dir / f"generation_{safe}.csv")
            study_c.append({"config": f"{provider}:{model}", **summary})
            for r in rows:
                reason = failure_reason(r)
                if reason:
                    failures.append({**r, "llm": f"{provider}:{model}", "reason": reason})
            log.info("%s:%s -> %s", provider, model, json.dumps(summary))
        timings["Study C"] = time.time() - t0

    total_time = time.time() - t_start

    # ---------------- report
    L: list[str] = []
    w = L.append
    w("# DocQuery AI — Experiment Report\n")
    w(f"**Run:** `{run_id}` · **Duration:** {total_time / 60:.1f} min · **Mode:** {'quick' if args.quick else 'full'}\n")
    w("This report is generated by `eval/run_experiments.py`. Raw per-question results and the full log are in "
      f"[`eval/results/run_{run_id}/`](../eval/results/run_{run_id}/).\n")

    w("## Key results\n")
    if study_a:
        top = max(study_a, key=lambda r: (r.get("recall@5", 0), r.get("mrr@10", 0)))
        dense = next((r for r in study_a if r["chunking"] == top["chunking"] and r["retrieval"] == "dense"), None)
        w(f"- **Best retrieval configuration:** {top['config']}: Recall@5 = {fmt(top.get('recall@5'))}, "
          f"MRR@10 = {fmt(top.get('mrr@10'))}.")
        if dense and top is not dense:
            w(f"- **Compared with dense-only search** (same chunking): Recall@5 went from {fmt(dense.get('recall@5'))} "
              f"to {fmt(top.get('recall@5'))}, and MRR@10 from {fmt(dense.get('mrr@10'))} to {fmt(top.get('mrr@10'))}.")
    if best:
        zero = find(0, "sentence", "on") or find(0, "word", "on")
        nodd = find(best["overlap"], "sentence", "off")
        ov = best["overlap"]
        ov_text = ("no overlap" if ov == 0 else f"{round(ov * 100)}% of chunk size" if ov < 1 else f"{ov:g} words")
        w(f"- **Chosen chunk overlap:** {ov_text}, sentence-aligned, with near-duplicate removal "
          "(highest Recall@5, then MRR@10, then the smaller overlap).")
        if zero and zero is not best:
            w(f"  - Compared with no overlap: Recall@5 went from {fmt(zero.get('recall@5'))} to {fmt(best.get('recall@5'))}, "
              f"and MRR@10 from {fmt(zero.get('mrr@10'))} to {fmt(best.get('mrr@10'))}.")
        if nodd:
            w(f"  - Near-duplicate share of the top 5 at this overlap: {fmt(nodd.get('dup_rate@5'))} without removal, "
              f"{fmt(best.get('dup_rate@5'))} with removal.")
    for r in study_c:
        w(f"- **{r['config']}:** answer F1 = {fmt(r.get('token_f1'))}, citation precision = "
          f"{fmt(r.get('citation_precision'))}, correct refusal/answer decisions = {fmt(r.get('abstention_correct'))}, "
          f"p50 latency = {r.get('p50_ms')} ms, p95 = {r.get('p95_ms')} ms.")
    if gstats["verified"] < gstats["total"]:
        w(f"- **Caution:** only {gstats['verified']} of {gstats['total']} gold questions were hand-verified.")
    w("")

    w("## Setup\n")
    w("**Environment**\n")
    w("| Item | Value |\n|---|---|")
    for k, v in env.items():
        w(f"| {k} | {v} |")
    w("\n**Documents** ({} files, {:,} words)\n".format(len(doc_rows), total_words))
    w("| File | Pages | Words |\n|---|---:|---:|")
    for r in doc_rows:
        w(f"| {r['file']} | {r['pages']} | {r['words']} |")
    w(f"\n**Gold question set:** `{args.gold}`: {gstats['total']} questions ({gstats['answerable']} answerable, "
      f"{gstats['unanswerable']} unanswerable; {gstats['verified']} hand-verified). Types: "
      + ", ".join(f"{k} {v}" for k, v in gstats["by type"].items()) + ".\n")
    w("**Base configuration**\n")
    w("```yaml\n" + yaml.safe_dump({k: base[k] for k in ["chunking", "embedding", "retrieval", "reranker", "gate"]},
                                   sort_keys=False) + "```\n")

    w("## Study A: retrieval methods\n")
    w("Each chunking strategy is indexed once, then searched with each retrieval method (near-duplicate removal on). "
      "Retrieval only, no LLM.\n")
    w(markdown_table(study_a, cols=["chunks", "recall@1", "recall@5", "recall@10", "mrr@10", "ndcg@10", "dup_rate@5", "p95_ms"]))
    w(f"\n_Time: {timings['Study A'] / 60:.1f} min_\n")

    w("## Study B: chunk overlap\n")
    w("Recursive chunking, hybrid search + re-ranking. Overlap is a fraction of the chunk size "
      f"({base['chunking']['chunk_size']} words). `word` carries a raw word window into the next chunk; `sentence` "
      "carries whole sentences only. `dedup` removes results that are mostly contained in a higher-ranked one.\n")
    w(markdown_table(study_b, cols=["chunks", "recall@1", "recall@5", "mrr@10", "ndcg@10", "dup_rate@5", "p95_ms"]))
    w(f"\n_Time: {timings['Study B'] / 60:.1f} min_\n")

    if study_c:
        w("## Study C: end-to-end answers\n")
        w(f"Recursive chunking, overlap {chosen_overlap:g} sentence-aligned, hybrid search + re-ranking, dedup on, "
          f"confidence gate on. {len(questions)} questions.\n")
        w(markdown_table(study_c, first="config", cols=["recall@5", "mrr@10", "token_f1", "numeric_exact",
                                                       "citation_precision", "unsupported_rate",
                                                       "abstention_correct", "p50_ms", "p95_ms"]))
        w(f"\n_Time: {timings['Study C'] / 60:.1f} min_\n")
        w("### Failure cases\n")
        if not failures:
            w("No failures were detected by the automatic checks.\n")
        else:
            counts = Counter(f["reason"] for f in failures)
            w("| Reason | Count |\n|---|---:|")
            for reason, n in counts.most_common():
                w(f"| {reason} | {n} |")
            w("\nExamples:\n")
            for f in failures[:8]:
                ans = " ".join(str(f.get("answer", "")).split())[:300]
                w(f"- **{f['id']}** ({f['llm']}, {f['reason']})  \n  Q: {f['question']}  \n"
                  f"  Expected: {f.get('expected') or '(should refuse)'}  \n  Got: {ans}")
            w("")

    w("## Metric definitions\n")
    w("| Metric | Meaning |\n|---|---|")
    for k, v in [("recall@k", "share of answerable questions with a relevant passage in the top k"),
                 ("mrr@10", "mean of 1/rank of the first relevant passage (0 if not in the top 10)"),
                 ("ndcg@10", "rank-weighted relevance of the top 10, normalised to 1"),
                 ("dup_rate@5", "share of the top 5 that are near-duplicates (≥ 80% term containment) of a higher-ranked result"),
                 ("token_f1", "word-overlap F1 between the generated and the expected answer"),
                 ("numeric_exact", "for numeric questions, share where every expected number appears in the answer"),
                 ("citation_precision", "share of cited passages that are relevant"),
                 ("unsupported_rate", "share of answer sentences flagged by the support check"),
                 ("abstention_correct", "share of questions where the answer/refuse decision was right"),
                 ("p50_ms / p95_ms", "median / 95th-percentile latency per question")]:
        w(f"| {k} | {v} |")
    w("\nA passage counts as relevant if it contains the gold evidence sentence, or comes from the gold source and page.\n")

    w("## Reproduce\n")
    w(f"```bash\n{cmd}\n```\n")
    w("## Author's observations\n")
    w("_Add your own interpretation here: what surprised you, why the best configuration won, and what you would try next._\n")

    report = "\n".join(L)
    exp_dir = ROOT / "docs" / "experiments"
    exp_dir.mkdir(parents=True, exist_ok=True)
    per_run = exp_dir / f"{run_id}.md"
    per_run.write_text(report.replace("](../eval/", "](../../eval/"))
    latest = ROOT / args.report
    latest.parent.mkdir(parents=True, exist_ok=True)
    latest.write_text(report)
    shutil.copy(per_run, run_dir / "report.md")
    log.info("Report written to %s and %s (%.1f min)", latest, per_run, total_time / 60)


if __name__ == "__main__":
    main()
